import {
  array,
  boolean,
  nullable,
  number,
  object,
  ref,
  revision,
  string,
  version,
} from './schema';

const points = array(ref('Point'));
const ids = array(string);
export const mapSchemas = {
  Route: object({
    id: string,
    number: string,
    name: string,
    color: string,
    overnight: boolean,
    scheduled: boolean,
  }),
  StopPattern: object(
    {
      routeId: string,
      stopIds: ids,
      headsign: string,
      pathId: string,
      directionId: { enum: [0, 1] },
    },
    ['routeId', 'stopIds', 'headsign'],
  ),
  Feature: object(
    {
      id: string,
      name: string,
      kind: { enum: ['stop', 'terminal'] },
      point: ref('Point'),
      routeIds: ids,
      accessible: nullable(boolean),
      boardingPoints: revision,
      platformNames: ids,
      destinations: { type: 'object', additionalProperties: ids },
      replacementRouteIds: ids,
      stopIds: ids,
      geographicPoints: array(ref('StopPosition')),
      edgeId: string,
      distanceAlongMetres: number,
    },
    [
      'id',
      'name',
      'kind',
      'point',
      'routeIds',
      'accessible',
      'boardingPoints',
      'platformNames',
      'destinations',
      'replacementRouteIds',
    ],
  ),
  Edge: object({
    id: string,
    a: string,
    b: string,
    points,
    sourcePoints: points,
    sourceDistances: array(number),
    lengthMetres: number,
    routeIds: ids,
    infrastructureIds: ids,
  }),
  ViewerMap: object(
    {
      format: { const: 'ttc-viewer-map' },
      schemaVersion: version,
      networkVersion: revision,
      features: array(ref('Feature')),
      routes: array(ref('Route')),
      edges: array(ref('Edge')),
      infrastructure: array(object({ id: string, name: string })),
      shoreline: points,
      labels: array(
        object({ text: string, kind: string, angle: number, point: ref('Point') }),
      ),
      northAngle: number,
      snapshot: string,
      bounds: object({ x: number, y: number, width: number, height: number }),
      geographicTransform: ref('GeographicTransform'),
      stopDirectory: ref('StopDirectory'),
      patterns: array(ref('StopPattern')),
      paths: array(
        object({
          id: string,
          routeIds: ids,
          edgeRefs: array(object({ edgeId: string, direction: { enum: [1, -1] } })),
        }),
      ),
    },
    [
      'features',
      'routes',
      'edges',
      'infrastructure',
      'shoreline',
      'labels',
      'northAngle',
      'snapshot',
      'bounds',
      'geographicTransform',
    ],
  ),
  SchematicMap: object(
    {
      format: { const: 'ttc-schematic-map' },
      schemaVersion: version,
      networkVersion: revision,
      generatedAt: { type: 'string', format: 'date-time' },
      generatorVersion: string,
      display: object({ geographicTransform: ref('GeographicTransform') }),
      stops: array(
        object({
          id: string,
          name: string,
          x: number,
          y: number,
          routeIds: ids,
          stopIds: ids,
        }),
      ),
      routes: array(
        object({ id: string, shortName: string, longName: string, color: string }, [
          'id',
        ]),
      ),
      patterns: array(ref('StopPattern')),
      graph: object({ edges: array(ref('Edge')) }),
      infrastructure: array(object({ id: string, name: string })),
      context: object({
        shoreline: points,
        labels: array(
          object({ text: string, kind: string, angle: number, point: ref('Point') }),
        ),
        north: object({ angle: number }),
      }),
      stopDirectory: ref('StopDirectory'),
    },
    [
      'schemaVersion',
      'networkVersion',
      'display',
      'stops',
      'routes',
      'patterns',
      'graph',
      'infrastructure',
      'context',
    ],
  ),
  ArtifactLink: object({
    format: string,
    schemaVersion: version,
    etag: string,
    url: { ...string, description: 'API-relative immutable artifact URL.' },
  }),
  ReleaseManifest: object({
    format: { const: 'ttc-release-manifest' },
    schemaVersion: version,
    networkVersion: revision,
    artifactId: revision,
    selectedBy: string,
    generatorVersion: string,
    map: {
      allOf: [
        ref('ArtifactLink'),
        object({ name: { enum: ['streetcar', 'snake', 'ttcstatus'] } }),
      ],
    },
    stops: nullable(ref('ArtifactLink')),
  }),
};
